"""Builds AllPlayers.csv and Assets/Scripts/PlayerCatalog.cs: 1,034 invented players in 50 invented clubs.
Every name is made up, so no licence is needed. Run: python3 tools/make_catalog.py"""
import csv, os, random

rng = random.Random(1034)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CITIES = ["Ashford","Brindle","Caldmoor","Dunwick","Eastvale","Fenwick","Galloway","Harrowgate","Ironbridge","Juniper Bay",
 "Kestrel","Lowmere","Marlowe","Northcliff","Oakhaven","Pinegrove","Quarry Hill","Ravenscar","Stonebridge","Thornbury",
 "Umberfield","Valewood","Westmarch","Yarrow","Zephyr Cove","Aldermoor","Bramblewick","Cinderford","Driftwood","Elmstead",
 "Foxhollow","Glenrock","Hollowbrook","Ivybridge","Kingsmere","Larkspur","Mistral Point","Netherby","Orchard Vale","Pebblecombe",
 "Redfern","Saltmarsh","Tidewater","Underhill","Vexford","Whitcombe","Wrenfield","Ambergate","Copperhill","Silverlake"]
SUFFIX = ["United","Rovers","Athletic","Town","City","Wanderers","Albion","Rangers","Dynamos","Olympic"]
FIRST = """Aiden Bruno Caleb Dario Elias Felix Gideon Hector Idris Jonas Kasper Leandro Matteo Nico Otis Pavel Quinn Rafael Soren Tomas
Ulises Viktor Wes Xavier Yusuf Zane Alvaro Bastian Cedric Dmitri Emil Fabian Gustavo Hugo Ivan Joaquin Kofi Luca Marek Nolan
Omar Pablo Rui Stefan Tariq Umar Valentin Wilmer Yannick Zeke Abel Brandon Cyrus Damon Ewan Farid Gael Hamza Ilias Jorge
Kwame Lars Mateus Nikolai Oren Paco Ramon Sven Tobias Uri Vito Wade Yago Zlatko Arlo Beau Callum Declan Enzo Flynn Gus""".split()
LAST = """Alderton Brandt Calloway Dvorak Eriksen Falconer Garrido Halvorsen Ibarra Jansen Kovacs Lindqvist Moreau Nakamura Okafor
Petrov Quintero Rasmussen Silva Thorne Urquhart Vasquez Whitlock Xander Yilmaz Zielinski Abara Barros Castellan Delacroix
Edmunds Ferreira Grimaldi Holt Ivanov Jovanovic Keller Lombardi Mbeki Novak Ortega Pellegrini Rossi Santoro Tavares Uzun
Voss Wolfe Yamada Zorn Acheampong Bellamy Cortez Dufresne Esposito Fontaine Greaves Hartmann Ishikawa Jorgensen Kinnear
Lacroix Marchetti Nyberg Oduya Pereira Quill Ronaldsen Stavros Tambo Ulloa Vermeer Winters Yeboah Zamora Arden Brook""".split()

CLUBS = []
for i, c in enumerate(CITIES):
    CLUBS.append(f"{c} {SUFFIX[i % len(SUFFIX)]}")

POS = ["GK"]*2 + ["CB"]*4 + ["LB"]*2 + ["RB"]*2 + ["CDM"]*2 + ["CM"]*3 + ["CAM"] + ["LW"] + ["RW"] + ["ST"]*2
assert len(POS) == 20

def value(r):
    return int(round(500_000 * 1.09 ** (r - 60), -5))

rows, used = [], set()
extra = 34                                    # 34 clubs carry a 21st player: 34*21 + 16*20 = 1034
for ci, club in enumerate(CLUBS):
    base = 68 + (ci * 7) % 17 + rng.randint(0, 6)      # club strength 68..90
    pos = POS + (["CM"] if ci < extra else [])
    club_rows = []
    for pi, p in enumerate(pos):
        while True:
            n = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
            if n not in used:
                used.add(n); break
        r = int(round(rng.gauss(base, 6)))
        club_rows.append([n, club, p, r])
    club_rows.sort(key=lambda x: -x[3])
    for k in (0, 1):                                    # each club has a couple of stand-outs
        if rng.random() < 0.55:
            club_rows[k][3] += rng.randint(5, 14)
    for row in club_rows:
        row[3] = max(55, min(115, row[3]))
        rows.append(row)

# Make sure the top of the game is deep enough for the Superstar pack (110+): lift the 9 best players.
for k, r in enumerate(sorted(rows, key=lambda r: -r[3])[:12]):
    r[3] = max(r[3], 110 + (k * 5) % 6)
assert len(rows) == 1034
rows.sort(key=lambda r: (r[1], -r[3]))
for i, r in enumerate(rows):
    r.insert(0, f"player_{i+1:04d}")                     # id,name,club,pos,rating

with open(os.path.join(ROOT, "AllPlayers.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["id", "name", "club", "position", "rating", "market_value"])
    for r in rows:
        w.writerow(r + [value(r[4])])

lines = ",\n".join('        "%s|%s|%s|%s|%d"' % (r[0], r[1], r[3], r[2], r[4]) for r in rows)
cs = f'''using System;
using System.Collections.Generic;

// GENERATED by tools/make_catalog.py - edit AllPlayers.csv / the script and regenerate.
// 1,034 invented players in {len(CLUBS)} invented clubs (no real names, so no licence needed).

[Serializable]
public class Footballer
{{
    public string id;
    public string playerName;
    public string position;     // GK, CB, LB, RB, CDM, CM, CAM, LW, RW, ST
    public int rating;
    public long marketValue;
}}

public static class PlayerCatalog
{{
    // id|name|position|club|rating
    private static readonly string[] Rows =
    {{
{lines}
    }};

    private static List<Footballer> cache;
    private static Dictionary<string, string> clubById;

    public static long ValueOf(int rating)
    {{
        return (long)(Math.Round(500000 * Math.Pow(1.09, rating - 60) / 100000.0) * 100000);
    }}

    private static void Load()
    {{
        if (cache != null) return;
        cache = new List<Footballer>();
        clubById = new Dictionary<string, string>();
        foreach (string row in Rows)
        {{
            string[] p = row.Split('|');
            int rating = int.Parse(p[4]);
            cache.Add(new Footballer {{ id = p[0], playerName = p[1], position = p[2], rating = rating, marketValue = ValueOf(rating) }});
            clubById[p[0]] = p[3];
        }}
    }}

    // A fresh list every call, so callers can sort or edit it freely.
    public static List<Footballer> Create()
    {{
        Load();
        List<Footballer> copy = new List<Footballer>(cache.Count);
        foreach (Footballer f in cache)
            copy.Add(new Footballer {{ id = f.id, playerName = f.playerName, position = f.position, rating = f.rating, marketValue = f.marketValue }});
        return copy;
    }}

    public static string ClubOf(string playerId)
    {{
        Load();
        string club;
        return clubById.TryGetValue(playerId, out club) ? club : "";
    }}
}}
'''
open(os.path.join(ROOT, "Assets", "Scripts", "PlayerCatalog.cs"), "w").write(cs)

